const defaultWorkspaceRoot = fileURLToPath(new URL("../../../../", import.meta.url));
const dnsLabel = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/;

/** `control` is the platform's reserved control-surface alias — never an app name. */
const notReserved = Schema.makeFilter((name: string) =>
  isReservedAppName(name)
    ? `"${RESERVED_APP_NAME}" is reserved for the platform control surface and cannot be an app name`
    : undefined
);

export const ScaffoldInput = Schema.Struct({
  name: Schema.String.check(Schema.isPattern(dnsLabel), notReserved),
  /**
   * Preview lineage (docs/previews-and-acl.md): when set, this app is a PR
   * preview of the named parent app — its own Worker/D1/hostname/OIDC client,
   * torn down wholesale on PR close. Cloudflare-only for now.
   */
  previewOf: Schema.optional(Schema.String.check(Schema.isPattern(dnsLabel))),
  previewPr: Schema.optional(Schema.String),
});

export interface ScaffoldOptions {
  readonly issuer?: string | undefined;
  readonly appsRoot?: string | undefined;
  readonly workspaceRoot?: string | undefined;
  readonly startupTimeoutMs?: number | undefined;
  readonly mode?: "local" | "cloudflare" | undefined;
  readonly cloudflare?: {
    readonly accountId: string;
    readonly alchemyHome: string;
    readonly workersSubdomain: string;
    /** Base domain app hostnames hang off of, e.g. `vibevarium.com`. */
    readonly domain: string;
    readonly routerNamespaceId: string;
    readonly zoneId: string;
  } | undefined;
  /** Casdoor DCR config for auto-registering each app's OIDC client. */
  readonly casdoor?: {
    readonly issuer: string;
    /** Organization dynamically-registered clients land in (default `vibevarium`). */
    readonly organization: string;
    /** The platform audience every app also accepts (Option B′). */
    readonly platformAudience: string;
  } | undefined;
  readonly github?: {
    readonly appId: string;
    /** Path to a PEM file on disk (env mode). */
    readonly privateKeyPath?: string | undefined;
    /** Inline PEM contents (secrets mode). Exactly one of the two is set. */
    readonly privateKey?: string | undefined;
    readonly installationId: number;
    readonly org: string;
  } | undefined;
}

export interface ScaffoldResult {
  readonly name: string;
  readonly url: string;
  readonly audience: string;
  readonly repoUrl: string;
  readonly processId: number;
  readonly hostname?: string | undefined;
  readonly deployment?: CloudflareDeployment | undefined;
  readonly directoryEntry: {
    readonly app: AppRegistration;
    readonly tools: ReadonlyArray<DirectoryTool>;
  };
}

const generatedFiles = (name: string): Readonly<Record<string, string>> => ({
  "package.json": `${JSON.stringify({
    name: `@vibevarium-app/${name}`,
    version: "0.0.1",
    private: true,
    type: "module",
    scripts: { start: "tsx src/main.ts" },
    dependencies: { "@vibevarium/template": "workspace:*" },
    devDependencies: { tsx: "^4.23.15" },
  }, null, 2)}\n`,
  "src/main.ts": `import { runTicketsServer } from "@vibevarium/template/server";\n\nrunTicketsServer();\n`,
  "README.md": `# ${name}\n\nGenerated by the Vibevarium scaffold spike. This wrapper intentionally shares the workspace template rather than forking it.\n`,
  ".gitignore": "node_modules/\napp.log\napp.pid\n",
});

const linkWorkspaceTemplate = (workspaceRoot: string, repo: GitRepo) =>
  attempt(async () => {
    const link = join(repo.directory, "node_modules", "@vibevarium", "template");
    await mkdir(dirname(link), { recursive: true });
    await symlink(relative(dirname(link), join(workspaceRoot, "packages", "template")), link, "dir");
  });

const respond = <A>(effect: Effect.Effect<A, ScaffoldError>, successStatus = 200) =>
  effect.pipe(
    Effect.tapDefect((cause) => Effect.logError("scaffold route defect", cause)),
    Effect.matchEffect({
      onFailure: (error) => HttpServerResponse.json({ error: error.message }, { status: error.status }),
      onSuccess: (value) => HttpServerResponse.json(value, { status: successStatus }),
    }),
  );

// The gate factory's exact requirement shape is the caller's business — it
// matches server.ts's `gated` (GUI session OR bearer, providing CurrentActor).
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Gated = <E, R>(
  handler: Effect.Effect<HttpServerResponse.HttpServerResponse, E, R>,
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
) => Effect.Effect<HttpServerResponse.HttpServerResponse, E, any>;

const registerGeneratedRoutes = (gated: Gated) =>
  HttpRouter.use((router) =>
    Effect.gen(function*() {
      const scaffold = yield* Scaffold;

      yield* router.add("POST", "/scaffold", gated(Effect.gen(function*() {
        const request = yield* HttpServerRequest;
        const body = yield* request.json.pipe(Effect.catch(() => Effect.succeed(undefined)));
        const decoded = yield* Schema.decodeUnknownEffect(ScaffoldInput)(body).pipe(Effect.result);
        if (Result.isFailure(decoded)) {
          return yield* HttpServerResponse.json({
            error: "Expected { name } with a unique, DNS-label-safe lower-kebab-case name (1-63 characters)",
            details: decoded.failure.message,
          }, { status: 400 });
        }
        const preview = decoded.success.previewOf === undefined
          ? undefined
          : { previewOf: decoded.success.previewOf, previewPr: decoded.success.previewPr ?? "" };
        const actor = yield* Effect.serviceOption(CurrentActor);
        const actorSub = Option.isSome(actor) ? actor.value.sub : undefined;
        return yield* respond(scaffold.create(decoded.success.name, preview, actorSub), 201);
      })));

      yield* router.add("DELETE", "/apps/:name", gated(Effect.gen(function*() {
        const params = yield* HttpRouter.params;
        const name = params.name;
        if (name === undefined || !dnsLabel.test(name)) {
          return yield* HttpServerResponse.json({ error: "Invalid app name" }, { status: 400 });
        }
        return yield* respond(scaffold.remove(name));
      })));
    })
  );

export class Scaffold extends Context.Service<Scaffold, {
  readonly create: (
    name: string,
    preview?: { readonly previewOf: string; readonly previewPr: string },
    /** The creator's sub (from CurrentActor at the gated route) — seeded as the app's ACL admin. */
    actorSub?: string,
  ) => Effect.Effect<ScaffoldResult, ScaffoldError>;
  readonly remove: (
    name: string,
  ) => Effect.Effect<{
    readonly name: string;
    readonly deleted: true;
    readonly repoKept?: string;
    readonly workerDeleted?: boolean;
    readonly d1Deleted?: boolean;
    readonly repoDeleted?: boolean;
  }, ScaffoldError>;
}>()("@vibevarium/control-plane/scaffold/Scaffold") {
  static readonly layer = (options: ScaffoldOptions = {}) =>
    Layer.effect(Scaffold)(Effect.gen(function*() {
      const registry = yield* Registry;
      const acl = yield* Acl;
      const directory = yield* Directory;
      const discovery = yield* Discovery;
      const proxy = yield* AppProxy;
      const mcpServer = yield* McpServer.McpServer;
      const git = yield* GitProvider;
      const processes = yield* Effect.acquireRelease(
        Effect.sync(() => new AppProcesses()),
        (apps) => Effect.promise(() => apps.stopAll()),
      );
      const workspaceRoot = options.workspaceRoot ?? defaultWorkspaceRoot;
      const appsRoot = options.appsRoot ?? join(workspaceRoot, "apps");
      const startupTimeoutMs = options.startupTimeoutMs ?? 20_000;
      const mode = options.mode ?? (options.cloudflare === undefined ? "local" : "cloudflare");
      const templateRoot = join(workspaceRoot, "packages", "template-cloudflare");
      const deployer = options.cloudflare === undefined
        ? undefined
        : new CloudflareDeployer(options.cloudflare);
      const routerBindings = options.cloudflare === undefined
        ? undefined
        : yield* loadRouterBindings(workspaceRoot, options.cloudflare.accountId);
      const routerDirectory = options.cloudflare === undefined
        ? undefined
        : new RouterDirectory({
            accountId: options.cloudflare.accountId,
            namespaceId: options.cloudflare.routerNamespaceId,
            zoneId: options.cloudflare.zoneId,
          });

      const register = Effect.fnUntraced(function*(
        name: string,
        url: string,
        oidcClientId?: string,
        preview?: { readonly previewOf: string; readonly previewPr: string },
        actorSub?: string,
      ) {
        const app = yield* registry.register({
          name,
          url,
          ...(oidcClientId === undefined ? {} : { oidcClientId }),
          ...(preview === undefined
            ? {}
            : { previewOf: preview.previewOf, previewPr: preview.previewPr }),
        });
        // Seed the creator as the app's ACL admin (docs/previews-and-acl.md
        // Part 2). Previews inherit the parent's ACL instead (no new rows).
        if (actorSub !== undefined && preview === undefined) {
          yield* acl.seedCreator(name, actorSub);
        }
        const discovered = yield* discovery.discoverApp(app);
        yield* syncGatewayTools.pipe(
          Effect.provideService(McpServer.McpServer, mcpServer),
          Effect.provideService(Directory, directory),
          Effect.provideService(AppProxy, proxy),
        );
        const current = yield* registry.get(name);
        const tools = (yield* directory.list()).filter((tool) => tool.appName === name);
        return {
          app: Option.getOrElse(current, () => app),
          tools,
          discoveryWarning: discovered.status === "down"
            ? `${discovered.error._tag}: ${discovered.error.message}`
            : undefined,
        };
      });

      const createLocal = Effect.fnUntraced(function*(name: string, actorSub?: string) {
        if (options.issuer === undefined || options.issuer.length === 0) {
          return yield* Effect.fail(new ScaffoldError(
            503,
            "Local scaffolding requires TERRARIUM_ISSUER so the generated app can verify OIDC tokens",
          ));
        }
        const audience = `${name}.vibevarium.local`;
        const port = yield* attempt(() => allocatePort());
        const repo = yield* git.createRepo(name, generatedFiles(name));
        yield* linkWorkspaceTemplate(workspaceRoot, repo);
        const running = yield* Effect.try({
          try: () => processes.start(name, repo.directory, port, {
            ...process.env,
            APP_NAME: name,
            PORT: String(port),
            TERRARIUM_AUTH: "on",
            TERRARIUM_ISSUER: options.issuer!,
            TERRARIUM_AUDIENCE: audience,
          }),
          catch: (cause) => asScaffoldError(cause),
        });
        yield* attempt(() => processes.writePidFile(running));
        yield* attempt(() => waitForHealth(running, startupTimeoutMs)).pipe(
          Effect.tapError(() => attempt(() => processes.stop(name))),
        );
        const directoryEntry = yield* register(name, `${running.url}/mcp`, undefined, undefined, actorSub);
        if (directoryEntry.discoveryWarning !== undefined) {
          return yield* Effect.fail(new ScaffoldError(
            502,
            `${name} booted but MCP discovery failed: ${directoryEntry.discoveryWarning}. Check DISCOVERY_TOKEN.`,
          ));
        }
        return {
          name,
          url: running.url,
          audience,
          repoUrl: repo.repoUrl,
          processId: running.pid,
          directoryEntry,
        } satisfies ScaffoldResult;
      });

      const createCloudflare = Effect.fnUntraced(function*(
        name: string,
        preview?: { readonly previewOf: string; readonly previewPr: string },
        actorSub?: string,
      ) {
        if (deployer === undefined) {
          return yield* Effect.fail(new ScaffoldError(503, "Cloudflare deployment is not configured"));
        }
        const appUrl = `https://${name}.${options.cloudflare!.domain}`;
        // Register the app's own OIDC client so it can run its auth-code flow.
        // Previews get their OWN client (own redirect URIs) — they never share
        // the parent app's client.
        const oidcClient = options.casdoor === undefined
          ? undefined
          : yield* createOidcClient(
              {
                issuer: options.casdoor.issuer,
                organization: options.casdoor.organization,
              },
              {
                name: `${name}.vibevarium`,
                callbackUrl: `${appUrl}/auth/callback`,
                logoutUrl: `${appUrl}/`,
              },
            );
        const files = yield* attempt(() => materializeCloudflareTemplate(templateRoot, name));
        const repo = yield* git.createRepo(name, files);
        const deployment = yield* attempt(() => deployer.deploy(name, repo.directory, oidcClient));
        yield* attempt(() => routerBindings!.add(name));
        yield* attempt(() => routerDirectory!.put(name, name));
        // Register the public hostname (not the workers.dev origin) so the
        // gallery + gateway point at the app's real URL. Preview lineage goes
        // on the row so the dashboard can group previews under their parent.
        const directoryEntry = yield* register(name, `${appUrl}/mcp`, oidcClient?.clientId, preview, actorSub);
        return {
          name,
          url: appUrl,
          audience: "unauthenticated-real-spike",
          repoUrl: repo.repoUrl,
          processId: 0,
          hostname: deployment.hostname,
          deployment,
          directoryEntry,
        } satisfies ScaffoldResult;
      });

      const syncCloudflareDirectory = Effect.fnUntraced(function*() {
        if (routerDirectory === undefined) return;
        const apps = yield* registry.list();
        yield* Effect.forEach(apps, (app) =>
          attempt(() => routerDirectory.put(app.name, app.name)),
          { discard: true },
        );
      });

      const create = Effect.fnUntraced(function*(
        name: string,
        preview?: { readonly previewOf: string; readonly previewPr: string },
        actorSub?: string,
      ) {
        if (!dnsLabel.test(name)) {
          return yield* Effect.fail(new ScaffoldError(400, "Invalid DNS-label-safe app name"));
        }
        const existing = yield* registry.get(name);
        if (Option.isSome(existing)) {
          return yield* Effect.fail(new ScaffoldError(409, `App ${name} is already registered`));
        }
        if (preview !== undefined) {
          // Previews are Cloudflare-only for now (docs/previews-and-acl.md):
          // cheap, instant, total teardown. The parent app must exist.
          if (mode !== "cloudflare") {
            return yield* Effect.fail(new ScaffoldError(400, "Preview deploys require the Cloudflare target"));
          }
          const parent = yield* registry.get(preview.previewOf);
          if (Option.isNone(parent)) {
            return yield* Effect.fail(new ScaffoldError(404, `Parent app ${preview.previewOf} is not registered`));
          }
        }
        return yield* (mode === "cloudflare" ? createCloudflare(name, preview, actorSub) : createLocal(name, actorSub));
      });

      const removeLocal = Effect.fnUntraced(function*(name: string) {
        yield* attempt(() => processes.stop(name));
        yield* registry.remove(name);
        return {
          name,
          deleted: true,
          repoKept: pathToFileURL(join(appsRoot, name)).href,
        } as const;
      });

      const removeCloudflare = Effect.fnUntraced(function*(name: string) {
        if (deployer === undefined) {
          return yield* Effect.fail(new ScaffoldError(503, "Cloudflare deployment is not configured"));
        }
        const appDirectory = join(appsRoot, name);
        // Delete the app's OIDC client before the registry row goes.
        const existing = yield* registry.get(name);
        if (options.casdoor !== undefined && Option.isSome(existing) && existing.value.oidcClientId !== null) {
          yield* deleteOidcClient(
            { issuer: options.casdoor.issuer, organization: options.casdoor.organization },
            existing.value.oidcClientId,
          ).pipe(
            Effect.tapError(() => Effect.logWarning(`Failed to delete OIDC client for ${name}`)),
            Effect.ignore,
          );
        }
        // Worker.lookup cannot resolve a deleted worker during the router redeploy.
        yield* attempt(() => routerBindings!.remove(name));
        yield* attempt(() => deployer.destroy(name, appDirectory));
        yield* attempt(() => routerDirectory!.delete(name));
        if (git.deleteRepo !== undefined) yield* git.deleteRepo(name);
        yield* registry.remove(name);
        return { name, deleted: true, workerDeleted: true, d1Deleted: true, repoDeleted: true } as const;
      });

      const remove = Effect.fnUntraced(function*(name: string) {
        const existing = yield* registry.get(name);
        if (Option.isNone(existing)) {
          return yield* Effect.fail(new ScaffoldError(404, `App ${name} is not registered`));
        }
        return yield* (mode === "cloudflare" ? removeCloudflare(name) : removeLocal(name));
      });

      yield* syncCloudflareDirectory();
      return Scaffold.of({ create, remove });
    })).pipe(
      Layer.provide(options.github === undefined
        ? LocalGitProvider.layer(options.appsRoot ?? join(options.workspaceRoot ?? defaultWorkspaceRoot, "apps"))
        : GitHubAppProvider.layer({
            ...options.github,
            appsRoot: options.appsRoot ?? join(options.workspaceRoot ?? defaultWorkspaceRoot, "apps"),
          })),
    );
  static readonly routes = registerGeneratedRoutes;
}

